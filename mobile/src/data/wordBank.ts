import {CefrLevel,StudyLanguage} from '@/types';

/** A word the daily drill can quiz in either direction. `alt` lists extra accepted Russian answers. */
export interface BankWord{id:string;word:string;translationRu:string;level:CefrLevel;categoryId:string;alt?:string[]}

type Row=[word:string,translationRu:string,categoryId:string,alt?:string[]];

const build=(language:StudyLanguage,rowsByLevel:Record<CefrLevel,Row[]>):BankWord[]=>
  (Object.entries(rowsByLevel) as [CefrLevel,Row[]][]).flatMap(([level,rows])=>
    rows.map(([word,translationRu,categoryId,alt])=>({id:`${language}:${word.toLowerCase()}`,word,translationRu,level,categoryId,alt})));

