export function createGitTask(instruction) {
  return `Выполни Git/GitHub-задачу владельца проекта: ${instruction}

Перед действием обязательно проверь git status, текущую ветку, remotes и релевантный diff. Не добавляй в commit .env, секреты, Expo-логи, __pycache__ и посторонние пользовательские файлы. Не используй force push, reset, rebase, удаление веток или откат изменений, если пользователь явно не потребовал именно это. Для GitHub используй существующую авторизацию gh CLI. После операции проверь итоговый Git/GitHub-статус и дай ссылки на созданные PR.`;
}

export function createPublishTask(description) {
  return `Опубликуй текущие полезные изменения FlipFox в репозитории words полным безопасным GitHub-процессом.

Контекст изменений от пользователя: ${description || "опубликовать текущие изменения"}

Обязательный порядок:
1. Проверь git status и diff. Не трогай и не добавляй .env, секреты, Expo-логи, __pycache__ и посторонние файлы.
2. Если релевантных изменений нет, ничего не публикуй и сообщи об этом.
3. Запусти уместные тесты и исправь только связанные с задачей ошибки.
4. До commit убедись, что работа идёт не в main; при необходимости создай ветку с префиксом codex/.
5. Добавь в индекс только релевантные файлы, проверь staged diff и создай один понятный commit.
6. Отправь ветку в origin и создай ровно один готовый PR в main. Если подходящий PR уже существует, используй его.
7. Дождись обязательных GitHub/Vercel checks. При ошибке не merge и верни причину со ссылкой.
8. Только после зелёных checks выполни обычный merge без force, удали опубликованную feature-ветку и синхронизируй локальный main.
9. Верни commit, ссылку на PR, результаты checks и merge commit.`;
}
